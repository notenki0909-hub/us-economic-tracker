/**
 * 各指標が「上がる・強まるとき」「下がる・弱まるとき」に、どの業種の売上・収益に追い風／向かい風に
 * なりやすいか。詳細画面の「この指標が動くと何が起きる？」の上がる／下がる欄に表示する
 * （impact.config.mjs が IMPACT[id].sectors として取り込む）。
 *
 * 方針：AIによる予測・分析ではなく、日本銀行・各国中央銀行・内閣府・民間シンクタンク等が解説している
 * 一般的な波及の考え方を、業種ごとに整理した固定の文章。個別企業の業績や株価を示すものではなく、
 * 「〜しやすい」という典型的な傾向のみを書く（投資助言ではない）。
 *
 * 書式：「業種:理由」を「|」でつなぐ。理由は短く、売上・収益・需要・コストのどれに働くかが分かるようにする。
 *   S(上がる:追い風, 上がる:向かい風, 下がる:追い風, 下がる:向かい風)
 * 該当する業種が特にない欄は空文字にする（画面には出さない）。
 */

const P = (s) =>
  s
    ? s.split("|").map((x) => {
        const i = x.indexOf(":");
        return [x.slice(0, i), x.slice(i + 1)];
      })
    : [];

const S = (upTail, upHead, downTail, downHead) => ({
  up: { tail: P(upTail), head: P(upHead) },
  down: { tail: P(downTail), head: P(downHead) },
});

